const DIGRAPHS: Record<string, string> = {
  "o'": "ў", "g'": "ғ", sh: "ш", ch: "ч", yo: "ё", yu: "ю", ya: "я", ye: "е",
};
const SINGLE: Record<string, string> = {
  a: "а", b: "б", d: "д", e: "е", f: "ф", g: "г", h: "ҳ", i: "и", j: "ж", k: "к", l: "л", m: "м", n: "н",
  o: "о", p: "п", q: "қ", r: "р", s: "с", t: "т", u: "у", v: "в", x: "х", y: "й", z: "з", c: "с", w: "в",
};
const KEEP = ["Workly", "Telegram", "SMS", "STIR"];

export function latinToCyrillic(input: string): string {
  const kept: string[] = [];
  let text = input.replace(/[ʻʼ‘’`]/g, "'");
  for (const word of KEEP) text = text.split(word).join(`\u0000${kept.push(word) - 1}\u0000`);
  // {0} kabi joy egalari ham saqlanadi
  text = text.replace(/\{\w+\}/g, (m) => `\u0000${kept.push(m) - 1}\u0000`);
  let out = "";
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === "\u0000") {
      const end = text.indexOf("\u0000", i + 1);
      out += kept[Number(text.slice(i + 1, end))];
      i = end;
      continue;
    }
    const pair = text.slice(i, i + 2);
    const low = pair.toLowerCase();
    const upper = ch !== ch.toLowerCase();
    if (DIGRAPHS[low]) {
      out += upper ? DIGRAPHS[low].toUpperCase() : DIGRAPHS[low];
      i++;
      continue;
    }
    const wordStart = i === 0 || !/\p{L}/u.test(text[i - 1]);
    const lc = ch.toLowerCase();
    let mapped: string;
    if (lc === "e" && wordStart) mapped = "э";
    else if (ch === "'") mapped = "ъ";
    else mapped = SINGLE[lc] ?? ch;
    out += upper ? mapped.toUpperCase() : mapped;
  }
  return out;
}

