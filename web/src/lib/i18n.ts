const cyrl = Object.fromEntries(
  Object.entries(uz).map(([k, v]) => [k, latinToCyrillic(v)]),
) as Record<MsgKey, string>;

const DICTS: Record<Lang, Record<MsgKey, string>> = { uz_latn: uz, uz_cyrl: cyrl, ru };

export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let text = DICTS[lang]?.[key] ?? uz[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

export const pickName = (names: Names, lang: Lang) => names[lang] || names.uz_latn;

export function errorKey(code: string): MsgKey | null {
  const key = `err.${code}` as MsgKey;
  return key in uz ? key : null;
}

export interface I18n {
  lang: Lang;
  setLang(lang: Lang): void;
  t(key: MsgKey, vars?: Record<string, string | number>): string;
}

export const I18nContext = createContext<I18n>({
  lang: "uz_latn",
  setLang: () => undefined,
  t: (key, vars) => translate("uz_latn", key, vars),
});

export const useI18n = () => useContext(I18nContext);
